/** Base path of the REST API, major version in the path (versioning.md). */
export const REST_API_BASE_PATH = '/api/v1'
export const REST_API_VERSION = 'v1'

export type HttpMethod = 'get' | 'post' | 'put' | 'delete'

/**
 * One REST route. A route can only name a registered action (`ActionId`), so
 * an unregistered handler cannot be declared; contract tests check that the
 * route's method fits the action's effect.
 */
export interface RouteContract {
  readonly operationId: string
  readonly method: HttpMethod
  /** Path below /api/v1 with {param} placeholders. */
  readonly path: string
  readonly summary: string
  readonly action: ActionId
  readonly pathParams: z.ZodObject
  readonly query?: z.ZodObject
  readonly body?: z.ZodType
  readonly response: { readonly status: 200 | 201 | 202; readonly schema: z.ZodType }
  /**
   * The response media type when it is not `application/json`. Only
   * `application/x-ndjson` exists: `response.schema` then describes one line
   * and the server sends the body as lines (audit export, audit.md §5.1).
   */
  readonly mediaType?: 'application/x-ndjson'
  /**
   * A request body that is not JSON (Wave 8, the profile picture): the raw
   * bytes in one of these media types, at most `maxBodyBytes`. `body` is
   * then absent; the use case checks the bytes themselves.
   */
  readonly rawBody?: { readonly mediaTypes: readonly string[] }
  /**
   * A response that is not JSON (Wave 8, the profile picture): the raw bytes
   * in one of these media types, with the headers the handler sets.
   * `response.schema` then only describes the bytes.
   */
  readonly rawResponse?: { readonly mediaTypes: readonly string[] }
  /** Route-specific error codes in addition to the codes every route can return. */
  readonly errors: readonly ErrorCode[]
  /**
   * The request body limit in bytes, counted while the body arrives and
   * before it is parsed (default {@link DEFAULT_BODY_LIMIT_BYTES}). Only the
   * routes that carry bundle text inline raise it.
   */
  readonly maxBodyBytes?: number
}

/** The body limit of a route that names none (64 KiB). */
export const DEFAULT_BODY_LIMIT_BYTES = 64 * 1024

/**
 * The body limit of a saved query's create and update (Wave 8): a SQL text
 * of 65,536 characters may take up to four UTF-8 bytes each, plus JSON
 * escaping, the name and the envelope.
 */
export const SAVED_QUERY_BODY_LIMIT_BYTES = 320 * 1024

