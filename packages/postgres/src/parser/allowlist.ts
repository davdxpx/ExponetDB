const FUNCTIONS: Readonly<Record<SupportedMajor, ReadonlySet<string>>> = {
  16: new Set([...BASE_FUNCTIONS, ...BY_MAJOR[16]]),
  17: new Set([...BASE_FUNCTIONS, ...BY_MAJOR[17]]),
  18: new Set([...BASE_FUNCTIONS, ...BY_MAJOR[18]]),
}

export function isAllowedFunction(major: SupportedMajor, name: string): boolean {
  return FUNCTIONS[major].has(name)
}

