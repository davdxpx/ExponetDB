import {
  type AuthenticationResponseJSON,
  generateAuthenticationOptions,
  generateRegistrationOptions,
  type PublicKeyCredentialCreationOptionsJSON,
  type PublicKeyCredentialRequestOptionsJSON,
  type RegistrationResponseJSON,
  verifyAuthenticationResponse,
  verifyRegistrationResponse,
} from '@simplewebauthn/server'
import type { AuthConfig } from '../config.ts'

/**
 * Passkeys (identity.md §2), the primary factor, through
 * `@simplewebauthn/server` (MIT): it parses CBOR, attestation and
 * authenticator data and verifies signatures; ExponetDB implements none of
 * that itself. ExponetDB adds:
 *
 * - origin and RP id from trusted configuration only, compared exactly;
 * - user verification required for registration and every assertion;
 * - discoverable credentials (`residentKey: required`): sign-in options name
 *   no account, so they cannot enumerate accounts; the assertion's user
 *   handle must be the owning identity's handle;
 * - a challenge is generated by the library from the CSPRNG, stored by the
 *   caller with a 5-minute lifetime and consumed once (replay fails);
 * - cross-origin (iframe) ceremonies are refused;
 * - attestation `none`: no enterprise attestation, no device identification;
 * - signature counters: a response whose counter does not increase is
 *   refused by the library when either counter is non-zero; synchronized
 *   passkeys that always report 0 are accepted;
 * - the response's `id` and `rawId` must equal the credential id inside the
 *   signed authenticator data;
 * - library errors never leave this module: every failure is `undefined`
 *   (their messages can contain the expected challenge).
 */
export const WEBAUTHN_TIMEOUT_MS = 300_000
/** ES256, EdDSA, RS256. */
export const SUPPORTED_ALGORITHMS = [-7, -8, -257] as const

export interface StoredPasskey {
  /** base64url of the raw credential id */
  readonly id: string
  readonly publicKey: Uint8Array
  readonly counter: number
  readonly transports: readonly string[]
}

export async function registrationOptions(
  config: AuthConfig,
  user: {
    readonly handle: Uint8Array
    readonly name: string
    readonly displayName: string
    readonly exclude: readonly { readonly id: string; readonly transports: readonly string[] }[]
  },
): Promise<PublicKeyCredentialCreationOptionsJSON> {
  return generateRegistrationOptions({
    rpName: config.rpName,
    rpID: config.rpId,
    userName: user.name,
    userID: Uint8Array.from(user.handle),
    userDisplayName: user.displayName,
    timeout: WEBAUTHN_TIMEOUT_MS,
    attestationType: 'none',
    excludeCredentials: user.exclude.map((c) => ({ id: c.id, transports: [...c.transports] })),
    authenticatorSelection: { residentKey: 'required', userVerification: 'required' },
    supportedAlgorithmIDs: [...SUPPORTED_ALGORITHMS],
  })
}

export async function authenticationOptions(
  config: AuthConfig,
  allow?: readonly { readonly id: string; readonly transports: readonly string[] }[],
): Promise<PublicKeyCredentialRequestOptionsJSON> {
  return generateAuthenticationOptions({
    rpID: config.rpId,
    timeout: WEBAUTHN_TIMEOUT_MS,
    userVerification: 'required',
    ...(allow === undefined
      ? {}
      : { allowCredentials: allow.map((c) => ({ id: c.id, transports: [...c.transports] })) }),
  })
}

function clientData(encoded: string): Record<string, unknown> | undefined {
  try {
    const parsed: unknown = JSON.parse(Buffer.from(encoded, 'base64url').toString('utf8'))
    return typeof parsed === 'object' && parsed !== null && !Array.isArray(parsed)
      ? Object.fromEntries(Object.entries(parsed))
      : undefined
  } catch {
    return undefined
  }
}

function sameOriginCeremony(encodedClientData: string): boolean {
  const data = clientData(encodedClientData)
  return data !== undefined && data['crossOrigin'] !== true && data['topOrigin'] === undefined
}

export interface RegisteredPasskey {
  readonly credentialId: Uint8Array
  readonly publicKey: Uint8Array
  readonly counter: number
  readonly transports: readonly string[]
  readonly backedUp: boolean
  readonly deviceType: 'singleDevice' | 'multiDevice'
}

export async function verifyRegistration(
  config: AuthConfig,
  response: RegistrationResponseJSON,
  expectedChallenge: string,
): Promise<RegisteredPasskey | undefined> {
  if (response.id !== response.rawId || !sameOriginCeremony(response.response.clientDataJSON)) {
    return undefined
  }
  try {
    const result = await verifyRegistrationResponse({
      response,
      expectedChallenge,
      expectedOrigin: config.publicOrigin,
      expectedRPID: config.rpId,
      requireUserPresence: true,
      requireUserVerification: true,
      supportedAlgorithmIDs: [...SUPPORTED_ALGORITHMS],
    })
    if (!result.verified || !result.registrationInfo.userVerified) {
      return undefined
    }
    const info = result.registrationInfo
    if (
      info.credential.id !== response.id ||
      info.origin !== config.publicOrigin ||
      (info.rpID !== undefined && info.rpID !== config.rpId)
    ) {
      return undefined
    }
    return {
      credentialId: new Uint8Array(Buffer.from(info.credential.id, 'base64url')),
      publicKey: Uint8Array.from(info.credential.publicKey),
      counter: info.credential.counter,
      transports: [...(info.credential.transports ?? [])],
      backedUp: info.credentialBackedUp,
      deviceType: info.credentialDeviceType,
    }
  } catch {
    return undefined
  }
}

export interface VerifiedAssertion {
  readonly newCounter: number
  readonly backedUp: boolean
}

export async function verifyAssertion(
  config: AuthConfig,
  response: AuthenticationResponseJSON,
  expectedChallenge: string,
  passkey: StoredPasskey,
  owner: { readonly userHandle: Uint8Array; readonly requireUserHandle: boolean },
): Promise<VerifiedAssertion | undefined> {
  if (response.id !== passkey.id || response.rawId !== passkey.id) {
    return undefined
  }
  if (!sameOriginCeremony(response.response.clientDataJSON)) {
    return undefined
  }
  const handle = response.response.userHandle
  if (handle === undefined) {
    if (owner.requireUserHandle) {
      return undefined
    }
  } else if (Buffer.from(handle, 'base64url').compare(Buffer.from(owner.userHandle)) !== 0) {
    return undefined
  }
  try {
    const result = await verifyAuthenticationResponse({
      response,
      expectedChallenge,
      expectedOrigin: config.publicOrigin,
      expectedRPID: config.rpId,
      requireUserVerification: true,
      credential: {
        id: passkey.id,
        publicKey: Uint8Array.from(passkey.publicKey),
        counter: passkey.counter,
        transports: [...passkey.transports],
      },
    })
    const info = result.authenticationInfo
    if (
      !result.verified ||
      !info.userVerified ||
      info.origin !== config.publicOrigin ||
      info.rpID !== config.rpId ||
      info.credentialID !== passkey.id
    ) {
      return undefined
    }
    return { newCounter: info.newCounter, backedUp: info.credentialBackedUp }
  } catch {
    return undefined
  }
}
