// sql_explain: agent without analyze, agent with analyze, human with analyze
for (const [mode, analyze, callerClass] of [
  ['agent', false, 'agent'],
  ['agent-analyze', true, 'agent'],
  ['human-analyze', true, 'human'],
]) {
  explain.forEach(([sql, expected], i) => {
    let exp = expected
    // EXPLAIN ANALYZE of a clean read is refused for an agent (caller class), and runs for a human.
    if (analyze && callerClass === 'agent' && expected === OK) exp = R
    out.push({
      id: `explain-${mode}-${String(i + 1).padStart(3, '0')}`,
      class: `explain-${mode}`,
      kind: 'explain',
      sql,
      expected: exp,
      analyze,
      callerClass,
    })
  })
}
