-- medium risk: a new table with row level security, a policy, grants and the updated_at trigger
CREATE TABLE public.feature_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  feature text NOT NULL,
  used_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX feature_usage_org_idx ON public.feature_usage (org_id, used_at DESC);
ALTER TABLE public.feature_usage ENABLE ROW LEVEL SECURITY;
CREATE POLICY feature_usage_select ON public.feature_usage FOR SELECT TO authenticated USING (org_id = (SELECT public.current_org_id()));
CREATE POLICY feature_usage_service ON public.feature_usage FOR ALL TO service_role USING (true) WITH CHECK (true);
GRANT SELECT, INSERT ON public.feature_usage TO authenticated;
GRANT ALL ON public.feature_usage TO service_role;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.feature_usage FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
