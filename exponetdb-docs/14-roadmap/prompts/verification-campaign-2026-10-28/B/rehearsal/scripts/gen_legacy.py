#!/usr/bin/env python3
"""Deterministic generator of a Supabase-like schema and its legacy migration history (tester S5).

usage: gen_legacy.py OUTDIR [--files 150] [--scale 1.0]

Writes under OUTDIR
  as_applied/   what really ran, in order, one file per migration (YYYYMMDDHHMMSS_slug.sql)
  migrations/   the repository state today: as_applied, with one file edited after apply, one file
                deleted (ledger entry without file), one file never recorded in the ledger
  ledger.sql    INSERTs for supabase_migrations.schema_migrations (version, name, statements[])
  hotfix.sql    applied out of band after the history (no file, no ledger row)
  data.sql      bulk data (generate_series), run after the history, as the superuser
  prereq_cluster.sql  roles (cluster-wide); prereq_db.sql extensions/schemas for one database
  MANIFEST.json counts the generator promises (tables, functions, policies, ...)
Everything is derived from random.Random(42): the same arguments give the same bytes.
"""
