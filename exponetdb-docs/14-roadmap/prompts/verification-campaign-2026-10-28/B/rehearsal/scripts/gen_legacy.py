def rls_sql(m):
    out = []
    for t in ('accounts', 'items', 'attachments'):
        out.append(f'alter table public.{m}_{t} enable row level security;')
        out.append(f'create policy "{m}_{t}_select" on public.{m}_{t} for select to authenticated using (org_id = (select public.current_org_id()));')
        out.append(f'create policy "{m}_{t}_modify" on public.{m}_{t} for all to authenticated using (public.is_org_admin(org_id)) with check (public.is_org_admin(org_id));')
        out.append(f'create policy "{m}_{t}_service" on public.{m}_{t} for all to service_role using (true) with check (true);')
    out.append(f'alter table public.{m}_settings enable row level security;')
    out.append(f'create policy "{m}_settings_member" on public.{m}_settings for select to authenticated using (public.is_org_member(org_id));')
    return '\n'.join(out)


