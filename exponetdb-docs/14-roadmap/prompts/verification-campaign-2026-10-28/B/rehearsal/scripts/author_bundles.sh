#!/usr/bin/env bash
# Authors the new bundles of the rehearsal in the project directory (after the baseline exists). usage: author_bundles.sh first|second
# first  = B1..B5, five bundles of mixed risk (planned and applied under load)
# second = B6, B7 (written after the backup; B7 is the one the point-in-time restore leaves out)
source /srv/work/s5/rehearsal/rh-lib.sh
cd "$PROJ"
# declare ID CLASS NOTES: the manifest's compatibility class, as the lint demands once it observes more than additive
declare() {
  local f; f="$(ls -d "$PROJ"/migrations/"${1}"_*)/migration.yaml"
  python3 - "$f" "$2" "$3" <<'PY2'
import sys
f, cls, notes = sys.argv[1:4]
s = open(f).read().replace("compatibility:\n  declared: additive\n", f"compatibility:\n  declared: {cls}\n  notes: |\n    {notes}\n")
open(f, 'w').write(s)
PY2
}
case "${1:?first|second}" in
first)
  VERIFY_SQL="SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='crm_items' AND column_name='note') AS ok;" \
  B1=$(mkb "$PROJ" add-crm-items-note <<'SQL'
-- low risk: a nullable column without default is a catalog-only change
ALTER TABLE public.crm_items ADD COLUMN IF NOT EXISTS note text;
COMMENT ON COLUMN public.crm_items.note IS 'free text note of the account manager';
SQL
)
  VERIFY_SQL="SELECT EXISTS (SELECT 1 FROM pg_catalog.pg_indexes WHERE schemaname='public' AND indexname='events_log_user_created_idx') AS ok;" \
  B2=$(mkb "$PROJ" index-events-log-user <<'SQL'
-- medium risk: a plain CREATE INDEX on the hottest table (5M rows) blocks its writers while it builds
CREATE INDEX events_log_user_created_idx ON public.events_log (user_id, created_at DESC);
SQL
)
  VERIFY_SQL="SELECT (SELECT relrowsecurity FROM pg_catalog.pg_class WHERE oid='public.feature_usage'::regclass) AS ok;" \
  B3=$(mkb "$PROJ" create-feature-usage <<'SQL'
-- medium risk: a new table with row level security, a policy, grants and the updated_at trigger
CREATE TABLE public.feature_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  feature text NOT NULL,
  used_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX feature_usage_org_idx ON public.feature_usage (org_id, used_at DESC);
ALTER TABLE public.feature_usage ENABLE ROW LEVEL SECURITY;
CREATE POLICY feature_usage_select ON public.feature_usage FOR SELECT TO authenticated USING (org_id = (SELECT public.current_org_id()));
CREATE POLICY feature_usage_service ON public.feature_usage FOR ALL TO service_role USING (true) WITH CHECK (true);
GRANT SELECT, INSERT ON public.feature_usage TO authenticated;
GRANT ALL ON public.feature_usage TO service_role;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.feature_usage FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
SQL
)
  VERIFY_SQL="SELECT (SELECT numeric_precision FROM information_schema.columns WHERE table_schema='public' AND table_name='crm_items' AND column_name='amount') = 16 AS ok;" \
  B4=$(mkb "$PROJ" crm-items-amount-precision <<'SQL'
-- high risk: a column type change that rewrites 1M rows under an ACCESS EXCLUSIVE lock
ALTER TABLE public.crm_items ALTER COLUMN amount TYPE numeric(16,4);
SQL
)
  VERIFY_SQL="SELECT to_regclass('public.hr_tags') IS NULL AS ok;" \
  B5=$(mkb "$PROJ" drop-hr-tags <<'SQL'
-- destructive: drops a table (empty here, but a drop all the same)
DROP TABLE public.hr_tags;
SQL
)
  declare "$B3" potentially_breaking "A new table with a policy and a trigger; no existing object changes, but the lint observes potentially_breaking."
  declare "$B4" data_rewrite "Changes the type of crm_items.amount (1M rows): the table is rewritten under ACCESS EXCLUSIVE."
  declare "$B5" destructive "Drops public.hr_tags; nothing reads it, but the drop cannot be undone without a backup."
  printf 'B1=%s\nB2=%s\nB3=%s\nB4=%s\nB5=%s\n' "$B1" "$B2" "$B3" "$B4" "$B5" | tee "$L/bundle-ids-first.env" ;;
second)
  VERIFY_SQL="SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='notifications' AND column_name='channel') AND to_regclass('public.rh_marker') IS NOT NULL AS ok;" \
  B6=$(mkb "$PROJ" notifications-channel-and-marker <<'SQL'
-- additive: a column with a constant default (no rewrite since PostgreSQL 11) and the marker table the writer fills
ALTER TABLE public.notifications ADD COLUMN IF NOT EXISTS channel text NOT NULL DEFAULT 'app';
CREATE TABLE public.rh_marker (id bigint PRIMARY KEY, ts timestamptz NOT NULL DEFAULT clock_timestamp());
GRANT ALL ON public.rh_marker TO service_role;
SQL
)
  VERIFY_SQL="SELECT to_regclass('public.region_settings') IS NOT NULL AS ok;" \
  B7=$(mkb "$PROJ" create-region-settings <<'SQL'
-- the last bundle: the point-in-time restore goes back to just before it
CREATE TABLE public.region_settings (region text PRIMARY KEY, config jsonb NOT NULL DEFAULT '{}'::jsonb);
INSERT INTO public.region_settings (region) VALUES ('eu'), ('us');
GRANT SELECT ON public.region_settings TO authenticated;
SQL
)
  printf 'B6=%s\nB7=%s\n' "$B6" "$B7" | tee "$L/bundle-ids-second.env" ;;
esac
