import { isObject } from './json.ts'

/**
 * Go types for the node protocol, generated from the node protocol JSON
 * Schema (contracts → JSON Schema → Go; one source of truth). Supports the
 * subset the protocol uses and refuses everything else loudly.
 */

const HEADER = '// Code generated by tooling/generators from packages/contracts. DO NOT EDIT.'
const INITIALISMS = new Set(['id', 'url', 'json', 'http', 'tls', 'cpu', 'wal'])

export function goFieldName(json: string): string {
  const words = json.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[ _]/)
  return words
    .map((w) =>
      INITIALISMS.has(w.toLowerCase())
        ? w.toUpperCase()
        : `${w.charAt(0).toUpperCase()}${w.slice(1)}`,
    )
    .join('')
}

interface Field {
  readonly goName: string
  readonly goType: string
  readonly tag: string
  readonly comment: string | undefined
}

interface Struct {
  readonly name: string
  readonly comment: string | undefined
  readonly fields: Field[]
}

class GoGenerator {
  readonly structs = new Map<string, Struct>()
  private readonly defs: Record<string, unknown>
  usesRawJson = false

  constructor(defs: Record<string, unknown>) {
    this.defs = defs
  }

  private resolveRef(ref: string): string {
    const name = ref.replace('#/$defs/', '')
    const def = this.defs[name]
    if (!isObject(def)) {
      throw new Error(`unresolved reference ${ref}`)
    }
    if (name === 'JsonValue') {
      throw new Error('JsonValue may only appear inside x-exponetdb-raw-json fields')
    }
    const typeName = goTypeName(name)
    if (!this.structs.has(typeName)) {
      this.structFrom(typeName, def)
    }
    return typeName
  }

  /** Go type of a schema used at a field position (without the nullability pointer). */
  typeOf(schema: Record<string, unknown>, context: string): string {
    if (schema['x-exponetdb-raw-json'] === true) {
      this.usesRawJson = true
      return 'json.RawMessage'
    }
    const ref = schema['$ref']
    if (typeof ref === 'string') {
      return this.resolveRef(ref)
    }
    const type = schema['type']
    switch (type) {
      case 'string':
        return 'string'
      case 'integer':
        return 'int64'
      case 'number':
        return 'float64'
      case 'boolean':
        return 'bool'
      case 'array': {
        const items = schema['items']
        if (!isObject(items)) {
          throw new Error(`${context}: array without items`)
        }
        return `[]${this.typeOf(items, singular(context))}`
      }
      case 'object':
        this.structFrom(context, schema)
        return context
      default:
        throw new Error(`${context}: unsupported schema ${JSON.stringify(schema).slice(0, 120)}`)
    }
  }

  structFrom(name: string, schema: Record<string, unknown>): void {
    if (schema['type'] !== 'object' || !isObject(schema['properties'])) {
      throw new Error(`${name}: expected an object schema with properties`)
    }
    if (schema['additionalProperties'] !== false) {
      throw new Error(`${name}: protocol objects must be closed`)
    }
    const placeholder: Struct = { name, comment: describe(schema), fields: [] }
    this.structs.set(name, placeholder)
    const required = new Set(Array.isArray(schema['required']) ? schema['required'] : [])
    for (const [json, raw] of Object.entries(schema['properties']).sort(([a], [b]) =>
      a < b ? -1 : 1,
    )) {
      if (!isObject(raw)) {
        throw new Error(`${name}.${json}: invalid property schema`)
      }
      const { schema: inner, nullable } = unwrapNullable(raw)
      const goName = goFieldName(json)
      const base = this.typeOf(inner, `${name}${goName}`)
      const optional = !required.has(json)
      const pointer = (nullable || optional) && base !== 'json.RawMessage' && !base.startsWith('[]')
      const goType = pointer ? `*${base}` : base
      const tag = `\`json:"${json}${optional ? ',omitempty' : ''}"\``
      placeholder.fields.push({ goName, goType, tag, comment: fieldComment(raw, inner) })
    }
  }
}

/** `HeartbeatRequestClusters` → `HeartbeatRequestCluster` for the element type of an array. */
function singular(name: string): string {
  if (name.endsWith('ies')) {
    return `${name.slice(0, -3)}y`
  }
  return name.endsWith('s') ? name.slice(0, -1) : `${name}Item`
}

function goTypeName(name: string): string {
  return name.replace(/^Node/, '')
}

function describe(schema: Record<string, unknown>): string | undefined {
  return typeof schema['description'] === 'string' ? schema['description'] : undefined
}

function fieldComment(
  outer: Record<string, unknown>,
  inner: Record<string, unknown>,
): string | undefined {
  const parts: string[] = []
  const d = describe(outer) ?? describe(inner)
  if (d !== undefined) {
    parts.push(d)
  }
  const values = inner['enum'] ?? (inner['const'] !== undefined ? [inner['const']] : undefined)
  if (Array.isArray(values)) {
    parts.push(`One of: ${values.map((v) => JSON.stringify(v)).join(', ')}.`)
  }
  if (typeof inner['pattern'] === 'string' && d === undefined) {
    parts.push(`Pattern: ${inner['pattern']}`)
  }
  return parts.length > 0 ? parts.join(' ') : undefined
}

function unwrapNullable(schema: Record<string, unknown>): {
  schema: Record<string, unknown>
  nullable: boolean
} {
  const anyOf = schema['anyOf']
  if (Array.isArray(anyOf)) {
    const nonNull = anyOf.filter((s) => !(isObject(s) && s['type'] === 'null'))
    const [only] = nonNull
    if (nonNull.length === 1 && anyOf.length === 2 && isObject(only)) {
      const { anyOf: _anyOf, ...rest } = schema
      return { schema: { ...rest, ...only }, nullable: true }
    }
    throw new Error(`unsupported union ${JSON.stringify(schema).slice(0, 120)}`)
  }
  const type = schema['type']
  if (Array.isArray(type)) {
    const nonNull = type.filter((t) => t !== 'null')
    if (nonNull.length === 1 && type.length === 2) {
      return { schema: { ...schema, type: nonNull[0] }, nullable: true }
    }
    throw new Error(`unsupported type list ${JSON.stringify(type)}`)
  }
  return { schema, nullable: false }
}

function comment(text: string | undefined, indent: string): string[] {
  if (text === undefined) {
    return []
  }
  return wrap(text, 76 - indent.length).map((line) => `${indent}// ${line}`.trimEnd())
}

function wrap(text: string, width: number): string[] {
  const lines: string[] = []
  let line = ''
  for (const word of text.replace(/\s+/g, ' ').trim().split(' ')) {
    if (line.length > 0 && line.length + 1 + word.length > width) {
      lines.push(line)
      line = word
    } else {
      line = line.length === 0 ? word : `${line} ${word}`
    }
  }
  if (line.length > 0) {
    lines.push(line)
  }
  return lines
}

/** Renders struct fields the way gofmt aligns them: one block per run of fields without comments between them. */
function renderFields(fields: readonly Field[]): string[] {
  const out: string[] = []
  let block: Field[] = []
  const flush = (): void => {
    const nameWidth = Math.max(...block.map((f) => f.goName.length))
    const typeWidth = Math.max(...block.map((f) => f.goType.length))
    for (const f of block) {
      out.push(`\t${f.goName.padEnd(nameWidth)} ${f.goType.padEnd(typeWidth)} ${f.tag}`)
    }
    block = []
  }
  for (const f of fields) {
    if (f.comment !== undefined) {
      if (block.length > 0) {
        flush()
      }
      out.push(...comment(f.comment, '\t'))
    }
    block.push(f)
  }
  if (block.length > 0) {
    flush()
  }
  return out
}

/** Generates `types_gen.go` from the node protocol JSON Schema document. */
export function generateGoProtocol(document: Record<string, unknown>): string {
  const defs = document['$defs']
  const messages = document['x-exponetdb-messages']
  if (!isObject(defs) || !isObject(messages)) {
    throw new Error('node protocol schema without $defs or messages')
  }
  const capabilities = document['x-exponetdb-capabilities']
  if (!isObject(capabilities)) {
    throw new Error('node protocol schema without capabilities')
  }
  const gen = new GoGenerator(defs)
  const messageTypes: [string, string][] = []
  for (const [name, schema] of Object.entries(messages)) {
    if (!isObject(schema)) {
      throw new Error(`message ${name} is not a schema`)
    }
    if (typeof schema['$ref'] === 'string') {
      messageTypes.push([name, gen.typeOf(schema, name)])
    } else {
      gen.structFrom(name, schema)
      messageTypes.push([name, name])
    }
  }
  const capabilityTypes: [string, string, string][] = []
  for (const [key, entry] of Object.entries(capabilities)) {
    if (!isObject(entry) || !isObject(entry['args']) || !isObject(entry['result'])) {
      throw new Error(`capability ${key} without args or result`)
    }
    capabilityTypes.push([
      key,
      gen.typeOf(entry['args'], `${key}Args`),
      gen.typeOf(entry['result'], `${key}Result`),
    ])
  }
  const lines: string[] = [
    HEADER,
    '',
    `// Package protocol holds the Go types of ${String(document['title'])}, generated`,
    '// from the node protocol JSON Schema. Field names and JSON tags follow the',
    '// contract exactly; optional members are pointers with omitempty, nullable',
    '// members are pointers that encode as null. In a job envelope and a',
    '// completion, capability arguments and results stay raw JSON; their strict',
    '// types come from NewCapabilityArgs and NewCapabilityResult.',
    'package protocol',
    '',
  ]
  if (gen.usesRawJson) {
    lines.push('import "encoding/json"', '')
  }
  const messageNames = new Set(messageTypes.map(([, t]) => t))
  lines.push(
    `// ProtocolID is the protocol identifier sent in the ${'X-Exponetdb-Protocol'} header.`,
  )
  lines.push(`const ProtocolID = ${JSON.stringify(String(document['title']))}`, '')
  for (const struct of [...gen.structs.values()].sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const intro = messageNames.has(struct.name)
      ? `${struct.name} is a message of ${String(document['title'])}.`
      : `${struct.name} is part of an ${String(document['title'])} message.`
    lines.push(...comment(struct.comment === undefined ? intro : `${intro} ${struct.comment}`, ''))
    lines.push(`type ${struct.name} struct {`, ...renderFields(struct.fields), '}', '')
  }
  lines.push('// NewMessage returns a new value of the message type with the given name, the')
  lines.push('// key used for fixtures and generated files.')
  lines.push('func NewMessage(name string) (any, bool) {', '\tswitch name {')
  for (const [name, typeName] of messageTypes.sort(([a], [b]) => (a < b ? -1 : 1))) {
    lines.push(`\tcase ${JSON.stringify(name)}:`, `\t\treturn &${typeName}{}, true`)
  }
  lines.push('\t}', '\treturn nil, false', '}', '')
  capabilityTypes.sort(([a], [b]) => (a < b ? -1 : 1))
  lines.push('// CapabilityKeys lists the capabilities of the catalog as name@major.')
  lines.push('var CapabilityKeys = []string{')
  for (const [key] of capabilityTypes) {
    lines.push(`\t${JSON.stringify(key)},`)
  }
  lines.push('}', '')
  for (const [fn, index, what] of [
    ['NewCapabilityArgs', 1, 'arguments'],
    ['NewCapabilityResult', 2, 'result'],
  ] as const) {
    lines.push(`// ${fn} returns a new value of the ${what} type of the capability`)
    lines.push('// name@major, or false for a capability outside the catalog.')
    lines.push(`func ${fn}(key string) (any, bool) {`, '\tswitch key {')
    for (const entry of capabilityTypes) {
      lines.push(`\tcase ${JSON.stringify(entry[0])}:`, `\t\treturn &${entry[index]}{}, true`)
    }
    lines.push('\t}', '\treturn nil, false', '}', '')
  }
  return lines.join('\n')
}
